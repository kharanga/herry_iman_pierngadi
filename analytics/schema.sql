CREATE TABLE IF NOT EXISTS shots (
    source VARCHAR NOT NULL CHECK (source IN ('shuttleset', 'own')),
    match_id VARCHAR NOT NULL,
    set_no INTEGER NOT NULL CHECK (set_no BETWEEN 1 AND 3),
    rally INTEGER NOT NULL,
    ball_round INTEGER NOT NULL,
    frame_num INTEGER,
    fps DOUBLE,
    player VARCHAR NOT NULL CHECK (player IN ('A', 'B', 'me', 'opp')),
    type_en VARCHAR,
    type_group VARCHAR CHECK (type_group IN ('serve', 'clear', 'drop', 'smash', 'net', 'lift', 'drive', 'unknown')),
    type_pred VARCHAR CHECK (type_pred IN ('serve', 'clear', 'drop', 'smash', 'net', 'lift', 'drive', 'unknown')),
    type_conf DOUBLE,
    backhand BOOLEAN,
    hit_x DOUBLE,
    hit_y DOUBLE,
    landing_x DOUBLE,
    landing_y DOUBLE,
    player_x DOUBLE,
    player_y DOUBLE,
    opponent_x DOUBLE,
    opponent_y DOUBLE,
    hit_zone VARCHAR CHECK (hit_zone IN ('front_forehand', 'front_middle', 'front_backhand', 'mid_forehand', 'mid_middle', 'mid_backhand', 'rear_forehand', 'rear_middle', 'rear_backhand')),
    landing_zone VARCHAR CHECK (landing_zone IN ('front_forehand', 'front_middle', 'front_backhand', 'mid_forehand', 'mid_middle', 'mid_backhand', 'rear_forehand', 'rear_middle', 'rear_backhand', 'not_over_net')),
    is_cross BOOLEAN,
    roundscore_me INTEGER,
    roundscore_opp INTEGER,
    getpoint_player VARCHAR CHECK (getpoint_player IN ('A', 'B', 'me', 'opp')),
    lose_reason VARCHAR
);
